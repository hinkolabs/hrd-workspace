#  슬라이드 노트 입력
# ══════════════════════════════════════════════════════════
def add_slide_notes():
    prs = Presentation(PPT_SRC)

    for slide_num, data in SCRIPTS.items():
        if slide_num < 1 or slide_num > len(prs.slides):
            continue
        slide  = prs.slides[slide_num - 1]
        title  = data.get('title',  '')
        time_  = data.get('time',   '')
        script = data.get('script', '').strip()
        tips   = data.get('tips',   '').strip()

        note_text = f"【{title}】\n⏱ {time_}\n\n{script}"
        if tips:
            note_text += f"\n\n---\n【강사 Tip】\n{tips}"

        notes_slide = slide.notes_slide
        tf = notes_slide.notes_text_frame
        tf.text = note_text

        print(f'  [Slide {slide_num}] 노트 입력 완료')

    prs.save(PPT_DST)
    print(f'\n  [PPT] 저장 완료: {PPT_DST}')


# ══════════════════════════════════════════════════════════
if __name__ == '__main__':
    print('=== Word 대본 생성 중 ===')
    build_word()
    print('\n=== 슬라이드 노트 입력 중 ===')
    add_slide_notes()
    print('\n✓ 모든 작업 완료')
