def build_word():
    doc = Document()

    # 페이지 여백 설정
    section = doc.sections[0]
    section.top_margin    = Cm(2.0)
    section.bottom_margin = Cm(2.0)
    section.left_margin   = Cm(2.5)
    section.right_margin  = Cm(2.5)

    # 스타일 헬퍼
    def h1(text):
        p = doc.add_paragraph()
        p.paragraph_format.space_before = DPt(18)
        p.paragraph_format.space_after  = DPt(4)
        run = p.add_run(text)
        run.bold = True
        run.font.size = DPt(16)
        run.font.color.rgb = DRGBColor(0x00, 0x91, 0x78)

    def h2(text):
        p = doc.add_paragraph()
        p.paragraph_format.space_before = DPt(10)
        p.paragraph_format.space_after  = DPt(2)
        run = p.add_run(text)
        run.bold = True
        run.font.size = DPt(13)
        run.font.color.rgb = DRGBColor(0x00, 0x4E, 0x42)

    def body(text, indent=False):
        p = doc.add_paragraph()
        p.paragraph_format.space_before = DPt(2)
        p.paragraph_format.space_after  = DPt(2)
        if indent:
            p.paragraph_format.left_indent = Cm(1.0)
        run = p.add_run(text)
        run.font.size = DPt(11)

    def tip_box(text):
        p = doc.add_paragraph()
        p.paragraph_format.space_before = DPt(6)
        p.paragraph_format.space_after  = DPt(6)
        p.paragraph_format.left_indent  = Cm(0.5)
        run = p.add_run('【강사 Tip】 ' + text)
        run.font.size = DPt(10)
        run.font.color.rgb = DRGBColor(0x88, 0x44, 0x00)
        run.italic = True

    def divider():
        p = doc.add_paragraph('─' * 80)
        p.paragraph_format.space_before = DPt(6)
        p.paragraph_format.space_after  = DPt(6)
        for run in p.runs:
            run.font.size = DPt(8)
            run.font.color.rgb = DRGBColor(0xCC, 0xCC, 0xCC)

    # 표지
    title_p = doc.add_paragraph()
    title_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    title_p.paragraph_format.space_before = DPt(40)
    r1 = title_p.add_run('하나증권 신입사원 AI 활용 교육\n')
    r1.bold = True
    r1.font.size = DPt(22)
    r1.font.color.rgb = DRGBColor(0x00, 0x91, 0x78)

    sub_p = doc.add_paragraph()
    sub_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r2 = sub_p.add_run('강사용 대본 (Instructor Script)')
    r2.font.size = DPt(16)
    r2.font.color.rgb = DRGBColor(0x00, 0x4E, 0x42)

    info_p = doc.add_paragraph()
    info_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    info_p.paragraph_format.space_before = DPt(20)
    r3 = info_p.add_run('총 27슬라이드 | 예상 소요시간: 약 4시간\n배포 금지 — 강사 전용')
    r3.font.size = DPt(11)
    r3.font.color.rgb = DRGBColor(0x66, 0x66, 0x66)

    doc.add_page_break()

    # 전체 구성 요약
    h1('📋 전체 교육 구성')
    table_data = [
        ('섹션', '내용', '슬라이드', '예상 시간'),
        ('오프닝', '표지 + 목차', '1~2', '8분'),
        ('1. 이론', 'AI 윤리 + 프롬프트 기술 + 할루시네이션', '3~11', '70분'),
        ('2. 실습 — DART', 'SK하이닉스 사업보고서 AI 분석', '12~18', '52분'),
        ('2. 실습 — Excel', '직원별 집계 + 오류 탐지', '19~21', '43분'),
        ('2. 실습 — 챗봇', 'Alli Works RAG 챗봇 이해 & 제작', '22~24', '33분'),
        ('3. 마무리', '이미지 카드 + Q&A + 클로징', '25~27', '40분'),
    ]
    tbl = doc.add_table(rows=len(table_data), cols=4)
    tbl.style = 'Table Grid'
    for r_idx, row_data in enumerate(table_data):
        for c_idx, cell_text in enumerate(row_data):
            cell = tbl.cell(r_idx, c_idx)
            cell.text = cell_text
            if r_idx == 0:
                for run in cell.paragraphs[0].runs:
                    run.bold = True
    doc.add_paragraph()

    doc.add_page_break()

    # 슬라이드별 대본
    h1('📝 슬라이드별 강사 대본')

    for slide_num in range(1, 28):
        data = SCRIPTS.get(slide_num, {})
        title  = data.get('title',  f'Slide {slide_num}')
        time_  = data.get('time',   '')
        script = data.get('script', '')
        tips   = data.get('tips',   '')

        divider()
        h2(f'▶ Slide {slide_num}  {title}')

        if time_:
            t_p = doc.add_paragraph()
            t_p.paragraph_format.space_after = DPt(4)
            t_run = t_p.add_run(f'⏱  {time_}')
            t_run.font.size = DPt(10)
            t_run.font.color.rgb = DRGBColor(0x00, 0x91, 0x78)
            t_run.bold = True

        if script:
            for line in script.strip().split('\n'):
                body(line)

        if tips:
            tip_box(tips)

    # 저장
    doc.save(DOC_DST)
    print(f'  [Word] 저장 완료: {DOC_DST}')


